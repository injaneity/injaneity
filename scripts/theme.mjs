// Derives the site palette from a terminal theme with pi's own `system` theme
// generator (https://earendil.com/posts/system-theme/), vendored unchanged in
// scripts/vendor/pi-theme, so the site shows the colours pi shows in that
// terminal. Pi keeps each token's hue from its ANSI slot and solves lightness
// from fitted contrast curves; this file only maps pi's tokens onto site roles.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateSystemThemeColors, wcagContrast } from './vendor/pi-theme/system-theme.js';

// Ghostty "novmbr"
export const terminal = {
  background: '#241d1a',
  foreground: '#c7b8ac',
  palette: [
    '#282a2e', '#9f6434', '#9dac5f', '#cca75f', '#2f7d7c', '#b5896e', '#52877f', '#c7b8ac',
    '#5d4e47', '#9f6434', '#9dac5f', '#cca75f', '#2f7d7c', '#b5896e', '#52877f', '#c7b8ac',
  ],
};

const toRgb = (hex) => ({ r: parseInt(hex.slice(1, 3), 16), g: parseInt(hex.slice(3, 5), 16), b: parseInt(hex.slice(5, 7), 16) });

export function contrast(a, b) {
  return wcagContrast(toRgb(a), toRgb(b));
}

/** Pi's token colours for the terminal theme; an empty string means pi uses the terminal's foreground. */
export function piColors() {
  const { colors } = generateSystemThemeColors({
    background: toRgb(terminal.background),
    foreground: toRgb(terminal.foreground),
    palette: terminal.palette.map(toRgb),
  });
  return Object.fromEntries(Object.entries(colors).map(([token, value]) => [token, value || terminal.foreground]));
}

// Site role → pi token. Roles pi has no exact twin for take the pi token used
// for the same job in its TUI.
const ROLES = {
  ink: 'text',
  muted: 'muted',
  'muted-soft': 'dim',
  rule: 'borderMuted',
  panel: 'toolPendingBg',
  selection: 'selectedBg',
  scrollbar: 'scrollbarThumb',
  accent: 'accent',
  'accent-hover': 'text',
  'link-accent': 'border',
  'link-accent-hover': 'mdLink',
  error: 'error',
  'inline-code': 'mdCode',
  'code-comment': 'syntaxComment',
  'code-keyword': 'syntaxKeyword',
  'code-function': 'syntaxFunction',
  'code-variable': 'syntaxVariable',
  'code-string': 'syntaxString',
  'code-number': 'syntaxNumber',
  'code-type': 'syntaxType',
  'code-operator': 'syntaxOperator',
  'code-punctuation': 'syntaxPunctuation',
  'code-addition': 'toolDiffAdded',
  'code-deletion': 'toolDiffRemoved',
};

export function deriveTheme() {
  const pi = piColors();
  return { paper: terminal.background, ...Object.fromEntries(Object.entries(ROLES).map(([role, token]) => [role, pi[token]])) };
}

export function themeCss(tokens = deriveTheme()) {
  const lines = Object.entries(tokens).map(([name, value]) => `  --${name}: ${value};`);
  return `/* Generated by scripts/theme.mjs from the Ghostty "novmbr" theme via pi's system theme. Do not edit by hand. */
:root {
  color-scheme: dark;
${lines.join('\n')}
  --link-wash: ${tokens['link-accent-hover']}40;
}
`;
}

export const themePath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/theme.css');

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(themePath, themeCss());
  console.log(`wrote ${path.relative(process.cwd(), themePath)}`);
}
