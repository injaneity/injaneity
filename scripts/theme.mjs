// Derives the site palette from a terminal theme with pi's own `system` theme
// generator (https://earendil.com/posts/system-theme/), vendored unchanged in
// scripts/vendor/pi-theme, so the site shows exactly the colours pi shows in
// that terminal. Every site colour is one of pi's tokens; the CSS uses each
// token for the same job pi does (headings mdHeading, links mdLink, ...).
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateSystemThemeColors, wcagContrast } from './vendor/pi-theme/system-theme.js';

// Ghostty "novmbr". In zane's terminal pi only receives the background: its
// screenshot shows pi's own family hues (cool greys, violet accent, green
// success panels), which is pi's "background only" tier, not novmbr's ANSI
// palette. Plain prose is drawn in the terminal's default foreground.
export const terminal = {
  background: '#241d1a',
  foreground: '#c7b8ac',
};

const toRgb = (hex) => ({ r: parseInt(hex.slice(1, 3), 16), g: parseInt(hex.slice(3, 5), 16), b: parseInt(hex.slice(5, 7), 16) });

export function contrast(a, b) {
  return wcagContrast(toRgb(a), toRgb(b));
}

/** Pi's token colours for a terminal that reports only its background. */
export function piColors() {
  const { colors } = generateSystemThemeColors({ background: toRgb(terminal.background) });
  return colors;
}

const kebab = (token) => token.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

/** Every pi token as a CSS custom property named after it (`mdHeading` → `--md-heading`). */
export function deriveTheme() {
  const pi = piColors();
  return { background: terminal.background, foreground: terminal.foreground, ...Object.fromEntries(Object.keys(pi).sort().map((token) => [kebab(token), pi[token]])) };
}

export function themeCss(tokens = deriveTheme()) {
  const lines = Object.entries(tokens).map(([name, value]) => `  --${name}: ${value};`);
  return `/* Generated by scripts/theme.mjs: pi's system theme on the Ghostty "novmbr" background. Do not edit by hand. */
:root {
  color-scheme: dark;
${lines.join('\n')}
}
`;
}

export const themePath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/theme.css');

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(themePath, themeCss());
  console.log(`wrote ${path.relative(process.cwd(), themePath)}`);
}
